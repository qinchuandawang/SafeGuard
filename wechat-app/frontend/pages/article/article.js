  loadRelatedArticles() {
    const currentId = this.data.article?.id;
    request({
      url: '/api/knowledge/articles',
      showLoading: false,
    }).then(res => {
      if (Array.isArray(res)) {
        const others = res.filter(item => item.id !== currentId);
        const shuffled = others.sort(() => Math.random() - 0.5).slice(0, 3);
        this.setData({ relatedArticles: shuffled });
      }
    }).catch(() => {
      // 静默失败
    });
  },

  // 返回上一页
  onBack() {
    const pages = getCurrentPages();
    const currentPage = pages[pages.length - 1];

    // 如果页面栈只有1个页面（直接打开文章详情），返回知识库 tab 页
    if (pages.length <= 1) {
      wx.switchTab({
        url: '/pages/knowledge/knowledge',
        fail: () => {
          wx.switchTab({
            url: '/pages/index/index',
          });
        }
      });
      return;
    }

    // 尝试返回上一页
    wx.navigateBack({
      delta: 1,
      fail: () => {
        // 返回失败，跳转到知识库 tab 页
        wx.switchTab({
          url: '/pages/knowledge/knowledge',
          fail: () => {
            wx.switchTab({
              url: '/pages/index/index',
            });
          }
        });
      }
    });
  },

  // 查看相关文章
  viewRelated(e) {
    const { id } = e.currentTarget.dataset;
    const article = this.data.relatedArticles.find(item => item.id === id);
    if (article) {
      // 从主页文章列表中查找完整文章数据
      const knowledgePages = getCurrentPages();
      let fullArticle = null;
      for (const page of knowledgePages) {
        if (page.route === 'pages/knowledge/knowledge' && page.data.articles) {
          const articles = Array.isArray(page.data.articles) ? page.data.articles : [];
          fullArticle = articles.find(a => a.id === id);
          break;
        }
      }
      if (fullArticle) {
        wx.navigateTo({
          url: `/pages/article/article?id=${id}&data=${encodeURIComponent(JSON.stringify(fullArticle))}`,
        });
      } else {
        // 找不到完整数据时，用相关信息重新加载
        wx.navigateTo({
          url: `/pages/article/article?id=${id}&data=${encodeURIComponent(JSON.stringify(article))}`,
        });
      }
    }
  },

